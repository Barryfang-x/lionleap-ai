const languageSelect = document.querySelector('#site-language');
const textRecords = [];
const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (node.parentElement.closest('script, style, .language-switch')) continue;
  const source = node.data.trim();
  if (translations[source]) textRecords.push({ node, original: node.data, source });
}
const attributeRecords = [];
document.querySelectorAll('[alt], [aria-label], meta[name="description"]').forEach(element => {
  for (const attribute of ['alt', 'aria-label', 'content']) {
    const source = element.getAttribute(attribute);
    if (source && translations[source]) attributeRecords.push({ element, attribute, source });
  }
});
let currentLanguage = 'zh-CN';
window.siteText = source => currentLanguage === 'en' ? (translations[source] || source) : source;
function applyLanguage(language) {
  currentLanguage = language === 'en' ? 'en' : 'zh-CN';
  document.documentElement.lang = currentLanguage;
  languageSelect.value = currentLanguage;
  for (const { node, original, source } of textRecords) {
    node.data = currentLanguage === 'en' ? original.replace(source, translations[source] + ' ') : original;
  }
  for (const { element, attribute, source } of attributeRecords) {
    element.setAttribute(attribute, window.siteText(source));
  }
  const menu = document.querySelector('.menu-toggle');
  menu.setAttribute('aria-label', window.siteText(menu.getAttribute('aria-expanded') === 'true' ? '关闭导航' : '打开导航'));
  const status = document.querySelector('.copy-status');
  if (status) status.textContent = '';
}
